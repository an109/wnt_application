
import '../../domain/entities/FlightBookEntity.dart';

class BookingModel extends FlightBookEntity {
  const BookingModel({
    required int id,
    required String flightType,
    required String flightNumber,
    required String fromCity,
    required String toCity,
    required String departureDate,
    String? returnDate,
    required int passengers,
    required String flightClass,
    dynamic user,
    required String guestReference,
    required String bookingToken,
    required List<dynamic> segments,
    String? name,
    required String email,
    required String phone,
    required String passportNumber,
    dynamic passportExpiry,
    required String bookingDate,
    required String pnr,
    required String tboBookingId,
    dynamic checkoutId,
    dynamic ccavenueOrderId,
    required String totalAmount,
    required String currency,
    String? paidVia,
    required Map<String, dynamic> ssrSelections,
    required List<PassengerDataEntity> passengersData,
    required String created,
    required String updated,
  }) : super(
    id: id,
    flightType: flightType,
    flightNumber: flightNumber,
    fromCity: fromCity,
    toCity: toCity,
    departureDate: departureDate,
    returnDate: returnDate,
    passengers: passengers,
    flightClass: flightClass,
    user: user,
    guestReference: guestReference,
    bookingToken: bookingToken,
    segments: segments,
    name: name,
    email: email,
    phone: phone,
    passportNumber: passportNumber,
    passportExpiry: passportExpiry,
    bookingDate: bookingDate,
    pnr: pnr,
    tboBookingId: tboBookingId,
    checkoutId: checkoutId,
    ccavenueOrderId: ccavenueOrderId,
    totalAmount: totalAmount,
    currency: currency,
    paidVia: paidVia,
    ssrSelections: ssrSelections,
    passengersData: passengersData,
    created: created,
    updated: updated,
  );

  factory BookingModel.fromJson(Map<String, dynamic> json) {
    return BookingModel(
      id: json['id'] ?? 0,
      flightType: json['flight_type'] ?? '',
      flightNumber: json['flight_number'] ?? '',
      fromCity: json['from_city'] ?? '',
      toCity: json['to_city'] ?? '',
      departureDate: json['departure_date'] ?? '',
      returnDate: json['return_date'],
      passengers: json['passengers'] ?? 0,
      flightClass: json['flight_class'] ?? '',
      user: json['user'],
      guestReference: json['guest_reference'] ?? '',
      bookingToken: json['booking_token'] ?? '',
      segments: json['segments'] ?? [],
      name: json['name'],
      email: json['email'] ?? '',
      phone: json['phone'] ?? '',
      passportNumber: json['passport_number'] ?? '',
      passportExpiry: json['passport_expiry'],
      bookingDate: json['bookingDate'] ?? '',
      pnr: json['pnr'] ?? '',
      tboBookingId: json['tbo_booking_id'] ?? '',
      checkoutId: json['checkout_id'],
      ccavenueOrderId: json['ccavenue_order_id'],
      totalAmount: json['total_amount'] ?? '',
      currency: json['currency'] ?? '',
      paidVia: json['paid_via'],
      ssrSelections: json['ssr_selections'] ?? {},
      passengersData: (json['passengers_data'] as List<dynamic>?)
          ?.map<PassengerDataEntity>((p) => PassengerDataModel.fromJson(p))
          .toList() ??
          [],
      created: json['created'] ?? '',
      updated: json['updated'] ?? '',
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'flight_type': flightType,
      'flight_number': flightNumber,
      'from_city': fromCity,
      'to_city': toCity,
      'departure_date': departureDate,
      'return_date': returnDate,
      'passengers': passengers,
      'flight_class': flightClass,
      'user': user,
      'guest_reference': guestReference,
      'booking_token': bookingToken,
      'segments': segments,
      'name': name,
      'email': email,
      'phone': phone,
      'passport_number': passportNumber,
      'passport_expiry': passportExpiry,
      'bookingDate': bookingDate,
      'pnr': pnr,
      'tbo_booking_id': tboBookingId,
      'checkout_id': checkoutId,
      'ccavenue_order_id': ccavenueOrderId,
      'total_amount': totalAmount,
      'currency': currency,
      'paid_via': paidVia,
      'ssr_selections': ssrSelections,
      'passengers_data': passengersData.map((p) => p.toString()).toList(),
      'created': created,
      'updated': updated,
    };
  }
}

class PassengerDataModel extends PassengerDataEntity {
  const PassengerDataModel({
    required String email,
    required String phone,
    required String title,
    required int paxType,
    dynamic tboMeal,
    dynamic tboSeat,
    required String lastName,
    required String firstName,
    required bool isLeadPax,
    required String passportNo,
    required String dateOfBirth,
    required String nationality,
    required String ticketNumber,
  }) : super(
    email: email,
    phone: phone,
    title: title,
    paxType: paxType,
    tboMeal: tboMeal,
    tboSeat: tboSeat,
    lastName: lastName,
    firstName: firstName,
    isLeadPax: isLeadPax,
    passportNo: passportNo,
    dateOfBirth: dateOfBirth,
    nationality: nationality,
    ticketNumber: ticketNumber,
  );

  factory PassengerDataModel.fromJson(Map<String, dynamic> json) {
    return PassengerDataModel(
      email: json['email'] ?? '',
      phone: json['phone'] ?? '',
      title: json['title'] ?? '',
      paxType: json['paxType'] ?? 0,
      tboMeal: json['tboMeal'],
      tboSeat: json['tboSeat'],
      lastName: json['lastName'] ?? '',
      firstName: json['firstName'] ?? '',
      isLeadPax: json['isLeadPax'] ?? false,
      passportNo: json['passportNo'] ?? '',
      dateOfBirth: json['dateOfBirth'] ?? '',
      nationality: json['nationality'] ?? '',
      ticketNumber: json['ticketNumber'] ?? '',
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'email': email,
      'phone': phone,
      'title': title,
      'paxType': paxType,
      'tboMeal': tboMeal,
      'tboSeat': tboSeat,
      'lastName': lastName,
      'firstName': firstName,
      'isLeadPax': isLeadPax,
      'passportNo': passportNo,
      'dateOfBirth': dateOfBirth,
      'nationality': nationality,
      'ticketNumber': ticketNumber,
    };
  }
}