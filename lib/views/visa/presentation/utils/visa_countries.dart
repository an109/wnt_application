/// Backend destination names that do not match [visaCountries] verbatim.
const Map<String, String> _nameAliases = {
  'united states of america': 'US',
  'usa': 'US',
  'uk': 'GB',
  'uae': 'AE',
  'lakshadeep': 'IN',
  'lakshadweep': 'IN',
  'st. kitts and nevis': 'KN',
  'swasiland': 'SZ',
  'ivory coast': 'CI',
  'republic of korea': 'KR',
  'hong kong - sar of china': 'HK',
  'saint-pierre-et-miquelon': 'PM',
  'wallis-et-futuna': 'WF',
  'reunion': 'RE',
};

/// ISO code for a destination name as stored in the backend, or null.
String? visaCountryCode(String name) {
  final n = name.toLowerCase().trim();
  if (n.isEmpty) return null;
  final alias = _nameAliases[n];
  if (alias != null) return alias;
  for (final c in visaCountries) {
    if (c.name.toLowerCase() == n) return c.code;
  }
  // "South Korea/ Republic of Korea", "Eswatini (Swasiland)" …
  for (final entry in _nameAliases.entries) {
    // Short keys like "uk" would also match inside "ukraine".
    if (entry.key.length > 4 && n.contains(entry.key)) return entry.value;
  }
  for (final c in visaCountries) {
    if (n.startsWith(c.name.toLowerCase())) return c.code;
  }
  return null;
}
