  final String name;
  final String code;
  const VisaCountry(this.name, this.code);

  /// Emoji flag built from the regional-indicator letters of [code].
  String get emoji => String.fromCharCodes(
        code.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 0x41),
      );
}

